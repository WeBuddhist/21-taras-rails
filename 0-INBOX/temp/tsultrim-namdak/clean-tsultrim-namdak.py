# Duplicate, more-degraded copyright/imprint block (repeat of lines 32-46).
DUP_IMPRINT_BLOCK = set(range(51, 66))  # 51-65
# Second, duplicate occurrence of the one-line dedication caption
# (first occurrence at line 49 is kept).
DUP_DEDICATION_LINE = {68}

FRONT_MATTER_REMOVE = STAMP_LINES | DUP_COVER_BLOCK | DUP_IMPRINT_BLOCK | DUP_DEDICATION_LINE

# --- TOC page-number-bleed fixes (1-indexed source line numbers) ---
