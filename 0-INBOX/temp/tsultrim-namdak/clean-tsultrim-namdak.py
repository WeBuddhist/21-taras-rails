# either).
HEADER_RULE_ACTIVE_FROM_LINE = 190

# The colophon chapter's heading text ("སྤར་བྱང་།") doubles as its own later
# running header. Keep the first (genuine heading) occurrence, remove the
# rest.
DUAL_PURPOSE_HEADER = "སྤར་བྱང"


def normalise_header(s: str) -> str:
    return s.strip().rstrip('།.༎༏་ ')


def clean(text: str) -> str:
    lines = text.split('\n')
    stats = {
        'nbt_replacements': 0,
        'stamp_lines_removed': 0,
        'dup_cover_block_removed': 0,
        'dup_imprint_block_removed': 0,
        'dup_dedication_removed': 0,
        'toc_digit_fixes': 0,
        'body_digit_bleed_fixes': 0,
        'page_number_lines_removed': 0,
        'roman_number_lines_removed': 0,
        'running_header_lines_removed': 0,
    }

    out = []
    seen_dual_purpose_header = False

    for idx, line in enumerate(lines):
        line_no = idx + 1  # 1-indexed, matches source line numbers used above

        # 1. Front-matter surgery: drop stamp lines / duplicate blocks outright.
        if line_no in FRONT_MATTER_REMOVE:
            if line_no in STAMP_LINES:
                stats['stamp_lines_removed'] += 1
            elif line_no in DUP_COVER_BLOCK:
                stats['dup_cover_block_removed'] += 1
            elif line_no in DUP_IMPRINT_BLOCK:
                stats['dup_imprint_block_removed'] += 1
            elif line_no in DUP_DEDICATION_LINE:
                stats['dup_dedication_removed'] += 1
            continue

        # 2. Non-breaking tsheg -> standard tsheg (safe everywhere).
        if NBT in line:
            stats['nbt_replacements'] += line.count(NBT)
            line = line.replace(NBT, STD_TSHEG)

        # 3. TOC page-number bleed.
        if line_no in TOC_LEADING_DIGITS:
            new_line = LEADING_DIGITS_RE.sub('', line)
            if new_line != line:
                stats['toc_digit_fixes'] += 1
            line = new_line
        if line_no in TOC_TRAILING_DIGITS:
            new_line = TRAILING_DIGITS_RE.sub('', line)
            if new_line != line:
                stats['toc_digit_fixes'] += 1
            line = new_line

        # 4. Isolated body page-number bleed.
        if line_no in BODY_TRAILING_DIGITS:
            new_line = TRAILING_DIGITS_RE.sub('', line)
            if new_line != line:
                stats['body_digit_bleed_fixes'] += 1
            line = new_line

        # 5. Blanket page-marker removal (arabic and roman numeral lines).
        if PAGE_NUM_LINE.match(line):
            stats['page_number_lines_removed'] += 1
            continue
        if ROMAN_NUM_LINE.match(line):
            stats['roman_number_lines_removed'] += 1
            continue

        # 6. Running-header removal.
        if line_no >= HEADER_RULE_ACTIVE_FROM_LINE:
            norm = normalise_header(line)
            if norm in RUNNING_HEADERS:
                stats['running_header_lines_removed'] += 1
                continue
            if norm.startswith(DUAL_PURPOSE_HEADER) and len(norm) <= len(DUAL_PURPOSE_HEADER) + 2:
                if seen_dual_purpose_header:
                    stats['running_header_lines_removed'] += 1
                    continue
                seen_dual_purpose_header = True

        out.append(line)

    result = '\n'.join(out)
    # Trim trailing whitespace on each line.
    result = '\n'.join(l.rstrip() for l in result.split('\n'))
    # Normalise blank lines: collapse runs of 2+ blank lines into exactly one.
    result = re.sub(r'\n{3,}', '\n\n', result)
    # Trim leading/trailing blank lines, ensure single trailing newline.
    result = result.strip('\n') + '\n'

    print("Done —")
    for k, v in stats.items():
        print(f"  {k}: {v}")
    return result


if __name__ == '__main__':
    raw = SOURCE.read_text(encoding='utf-8')
    cleaned = clean(raw)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(cleaned, encoding='utf-8')
    print(f"Written to: {OUTPUT}")
