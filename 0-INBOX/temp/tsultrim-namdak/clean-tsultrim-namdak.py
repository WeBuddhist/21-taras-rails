TOC_TRAILING_DIGITS = {147, 149, 151}       # strip trailing " <digits>"
LEADING_DIGITS_RE = re.compile(r'^[0-9]+')
TRAILING_DIGITS_RE = re.compile(r'\s+[0-9]+\s*$')

# Isolated body-text page-number bleed (see docstring).
BODY_TRAILING_DIGITS = {2440}

# --- Running-header canonical forms (normalised: trailing punctuation and
# whitespace stripped) — removed wherever they recur as a running header.
