import re
from pathlib import Path

SOURCE = Path("0-INBOX/temp/wf/c17.txt")
OUTPUT = Path("0-INBOX/temp/tsultrim-namdak/cleaned.md")

NBT = '༌'        # non-breaking tsheg ༌
STD_TSHEG = '་'  # standard tsheg ་

PAGE_NUM_LINE = re.compile(r'^\s*[0-9]+\s*$')
ROMAN_NUM_LINE = re.compile(r'^\s*[ivxIVX]+\s*$')

# --- Front-matter surgery (1-indexed source line numbers; see docstring) ---
# Library archival stamp lines (garbled OCR of a Palpung shelf-mark, never
